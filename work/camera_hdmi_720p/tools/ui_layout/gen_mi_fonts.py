#!/usr/bin/env python3
"""gen_mi_fonts.py — MiSans Medium 1-bit ROMs for count / ball ID / DETECTED / test pattern.

生成：
    rtl/video/mi_digit_rom.v       count 30x34, ball-ID 8x12, small 16x20
    rtl/video/detected_text_rom.v  "DETECTED " 96x20
    rtl/video/tp_text_rom.v        "HDMI TEST 1280X720" 288x20
    tools/ui_layout/misans_more_preview.png
"""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]
FONT = Path(r"C:\Users\Z___C\Documents\NUEDC\sdcard\ball_balance\fonts\MiSans-Medium.ttf")
OUT_DIR = PROJECT / "rtl" / "video"
PREVIEW = HERE / "misans_more_preview.png"

TEXTS = [
    ("detected", "DETECTED ", 96, 20, (0x8B, 0xE9, 0xFD)),
    ("tp", "HDMI TEST 1280X720", 288, 20, (0xFF, 0xFF, 0xFF)),
    ("tp_attr", "MiSans by Xiaomi", 160, 20, (0xFF, 0xFF, 0xFF)),
]
CELLS = [
    ("cnt", 30, 34, 34, (0x00, 0xE6, 0xFF)),
    ("id", 8, 12, 12, (0xFF, 0xFF, 0xFF)),
    ("sm", 16, 20, 20, (0x9A, 0xA7, 0xBD)),
]


def render_text(text, box_w, box_h):
    size = box_h
    while size > 6:
        font = ImageFont.truetype(str(FONT), size)
        bbox = font.getbbox(text)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if tw <= box_w - 2 and th <= box_h:
            break
        size -= 1
    font = ImageFont.truetype(str(FONT), size)
    bbox = font.getbbox(text)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    img = Image.new("L", (box_w, box_h), 0)
    draw = ImageDraw.Draw(img)
    draw.text((0 - bbox[0], (box_h - th) // 2 - bbox[1]), text, font=font, fill=255)
    return img.point(lambda v: 255 if v >= 128 else 0, "1"), size, (tw, th)


def render_digit(d, cw, ch, size):
    text = str(d)
    font = ImageFont.truetype(str(FONT), size)
    bbox = font.getbbox(text)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    img = Image.new("L", (cw, ch), 0)
    draw = ImageDraw.Draw(img)
    x = (cw - tw) // 2 - bbox[0]
    y = (ch - th) // 2 - bbox[1]
    draw.text((x, y), text, font=font, fill=255)
    return img.point(lambda v: 255 if v >= 128 else 0, "1"), (tw, th)


def row_value(mask, y):
    v = 0
    for x in range(mask.width):
        if mask.getpixel((x, y)):
            v |= 1 << x
    return v


def emit_rows(out, prefix, mask):
    width = mask.width
    hexw = (width + 3) // 4
    for y in range(mask.height):
        out.append(f"    localparam [{width - 1}:0] {prefix}_ROW{y} = {width}'h{row_value(mask, y):0{hexw}x};")


def emit_text_function(out, name, x_width, y_width, rows, prefix):
    out.append(f"    function {name};")
    out.append(f"        input [{x_width - 1}:0] x;")
    out.append(f"        input [{y_width - 1}:0] y;")
    out.append("        begin")
    out.append("            case (y)")
    for y in range(rows):
        out.append(f"                {y_width}'d{y}: {name} = {prefix}_ROW{y}[x];")
    out.append(f"                default: {name} = 1'b0;")
    out.append("            endcase")
    out.append("        end")
    out.append("    endfunction")
    out.append("")


def emit_digit_function(out, name, cell_w, cell_h, x_width, y_width, masks, prefix):
    out.append(f"    function {name};")
    out.append("        input [3:0] d;")
    out.append(f"        input [{x_width - 1}:0] x;")
    out.append(f"        input [{y_width - 1}:0] y;")
    out.append("        begin")
    out.append("            case (d)")
    for d, mask in enumerate(masks):
        out.append(f"                4'd{d}: begin")
        out.append("                    case (y)")
        for y in range(cell_h):
            out.append(f"                        {y_width}'d{y}: {name} = {prefix}{d}_ROW{y}[x];")
        out.append(f"                        default: {name} = 1'b0;")
        out.append("                    endcase")
        out.append("                end")
    out.append(f"                default: {name} = 1'b0;")
    out.append("            endcase")
    out.append("        end")
    out.append("    endfunction")
    out.append("")


def main():
    texts = {}
    for name, text, w, h, _ in TEXTS:
        mask, size, dim = render_text(text, w, h)
        texts[name] = mask
        print(f"{name}: {text!r} {w}x{h} font={size}px text={dim[0]}x{dim[1]}")

    cells = {}
    for name, cw, ch, size, _ in CELLS:
        masks = []
        for d in range(10):
            m, dim = render_digit(d, cw, ch, size)
            masks.append(m)
        cells[name] = masks
        print(f"{name}: {cw}x{ch} font={size}px digit0={dim[0]}x{dim[1]}")

    # ---- detected_text_rom.v ----
    out = []
    out.append("// ============================================================")
    out.append("// detected_text_rom.v — MiSans Medium 1-bit 'DETECTED ' prefix")
    out.append("// Generated by tools/ui_layout/gen_mi_fonts.py")
    out.append("// ============================================================")
    out.append("")
    out.append("module detected_text_rom (")
    out.append("    input  wire [6:0] I_X,")
    out.append("    input  wire [4:0] I_Y,")
    out.append("    output wire       O_BIT")
    out.append(");")
    out.append("")
    emit_rows(out, "DET", texts["detected"])
    out.append("")
    emit_text_function(out, "F_det", 7, 5, texts["detected"].height, "DET")
    out.append("    assign O_BIT = F_det(I_X, I_Y);")
    out.append("")
    out.append("endmodule")
    out.append("")
    (OUT_DIR / "detected_text_rom.v").write_text("\n".join(out), encoding="utf-8")
    print("wrote detected_text_rom.v")

    # ---- tp_text_rom.v ----
    out = []
    out.append("// ============================================================")
    out.append("// tp_text_rom.v — MiSans Medium 1-bit 'HDMI TEST 1280X720'")
    out.append("// Generated by tools/ui_layout/gen_mi_fonts.py")
    out.append("// ============================================================")
    out.append("")
    out.append("module tp_text_rom (")
    out.append("    input  wire [8:0] I_X,")
    out.append("    input  wire [4:0] I_Y,")
    out.append("    output wire       O_BIT")
    out.append(");")
    out.append("")
    emit_rows(out, "TP", texts["tp"])
    out.append("")
    emit_text_function(out, "F_tp", 9, 5, texts["tp"].height, "TP")
    out.append("    assign O_BIT = F_tp(I_X, I_Y);")
    out.append("")
    out.append("endmodule")
    out.append("")
    (OUT_DIR / "tp_text_rom.v").write_text("\n".join(out), encoding="utf-8")
    print("wrote tp_text_rom.v")

    # ---- tp_attr_text_rom.v ----
    out = []
    out.append("// ============================================================")
    out.append("// tp_attr_text_rom.v — MiSans Medium 1-bit 'MiSans by Xiaomi'")
    out.append("// Generated by tools/ui_layout/gen_mi_fonts.py")
    out.append("// ============================================================")
    out.append("")
    out.append("module tp_attr_text_rom (")
    out.append("    input  wire [7:0] I_X,")
    out.append("    input  wire [4:0] I_Y,")
    out.append("    output wire       O_BIT")
    out.append(");")
    out.append("")
    emit_rows(out, "TPA", texts["tp_attr"])
    out.append("")
    emit_text_function(out, "F_tpa", 8, 5, texts["tp_attr"].height, "TPA")
    out.append("    assign O_BIT = F_tpa(I_X, I_Y);")
    out.append("")
    out.append("endmodule")
    out.append("")
    (OUT_DIR / "tp_attr_text_rom.v").write_text("\n".join(out), encoding="utf-8")
    print("wrote tp_attr_text_rom.v")

    # ---- mi_digit_rom.v ----
    out = []
    out.append("// ============================================================")
    out.append("// mi_digit_rom.v — MiSans Medium 1-bit digits")
    out.append("//   count  30x34 x10   (5-digit HDMI count)")
    out.append("//   id      8x12 x10   (ball box ID)")
    out.append("//   small  16x20 x10   (DETECTED digit)")
    out.append("// Generated by tools/ui_layout/gen_mi_fonts.py")
    out.append("// ============================================================")
    out.append("")
    out.append("module mi_digit_rom (")
    out.append("    input  wire [3:0] I_CNT_DIGIT,")
    out.append("    input  wire [4:0] I_CNT_X,")
    out.append("    input  wire [5:0] I_CNT_Y,")
    out.append("    output wire       O_CNT,")
    out.append("    input  wire [3:0] I_ID_DIGIT,")
    out.append("    input  wire [3:0] I_ID_X,")
    out.append("    input  wire [3:0] I_ID_Y,")
    out.append("    output wire       O_ID,")
    out.append("    input  wire [3:0] I_SM_DIGIT,")
    out.append("    input  wire [3:0] I_SM_X,")
    out.append("    input  wire [4:0] I_SM_Y,")
    out.append("    output wire       O_SM")
    out.append(");")
    out.append("")
    for name, cw, ch, _, _ in CELLS:
        for d, mask in enumerate(cells[name]):
            emit_rows(out, f"{name.upper()}{d}", mask)
        out.append("")
    emit_digit_function(out, "F_cnt", 30, 34, 5, 6, cells["cnt"], "CNT")
    emit_digit_function(out, "F_id", 8, 12, 4, 4, cells["id"], "ID")
    emit_digit_function(out, "F_sm", 16, 20, 4, 5, cells["sm"], "SM")
    out.append("    assign O_CNT = F_cnt(I_CNT_DIGIT, I_CNT_X, I_CNT_Y);")
    out.append("    assign O_ID  = F_id (I_ID_DIGIT,  I_ID_X,  I_ID_Y);")
    out.append("    assign O_SM  = F_sm (I_SM_DIGIT,  I_SM_X,  I_SM_Y);")
    out.append("")
    out.append("endmodule")
    out.append("")
    (OUT_DIR / "mi_digit_rom.v").write_text("\n".join(out), encoding="utf-8")
    print("wrote mi_digit_rom.v")

    # ---- preview ----
    scale = 4
    sheet = Image.new("RGB", (1300, 900), (10, 16, 26))
    d = ImageDraw.Draw(sheet)
    small = ImageFont.truetype(str(FONT), 12)
    y = 10
    for name, _, w, h, color in TEXTS:
        m = texts[name]
        d.text((8, y), f"{name}: {w}x{h}", font=small, fill=(180, 200, 230))
        y += 14
        big = m.convert("RGB").resize((w * scale, h * scale), Image.NEAREST)
        px = big.load()
        for yy in range(big.height):
            for xx in range(big.width):
                px[xx, yy] = color if px[xx, yy][0] else (10, 16, 26)
        sheet.paste(big, (8, y))
        y += h * scale + 10
    for name, cw, ch, _, color in CELLS:
        d.text((8, y), f"{name}: {cw}x{ch}", font=small, fill=(180, 200, 230))
        y += 14
        for i, m in enumerate(cells[name]):
            big = m.convert("RGB").resize((cw * scale, ch * scale), Image.NEAREST)
            px = big.load()
            for yy in range(big.height):
                for xx in range(big.width):
                    px[xx, yy] = color if px[xx, yy][0] else (10, 16, 26)
            sheet.paste(big, (8 + i * (cw * scale + 4), y))
        y += ch * scale + 10
    sheet.save(PREVIEW)
    print("wrote", PREVIEW)


if __name__ == "__main__":
    main()
