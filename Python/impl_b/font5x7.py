# -*- coding: utf-8 -*-
"""
font5x7.py -- 5x7 字模（与 cv_top.v 的 f_digit 逐位一致）
==========================================================
FPGA 的 ID 是 4 位（0~f），叠加时用 5x7 点阵画在框的左上角。
本文件把 cv_top.v 第 397~420 行 f_digit 的位图原样搬来，
保证 PC 端画出的 ID 数字与 FPGA 上板**逐位相同**。

位序约定：每行 5 位，bit4 = 最左列，bit0 = 最右列（与 RTL 一致）。
"""
import numpy as np

# key: 0~f 的十六进制 ID 值 -> 7 行 x 5 位
FONT_5x7 = {
    0x0: (0b01110, 0b10001, 0b10011, 0b10101, 0b11001, 0b10001, 0b01110),
    0x1: (0b00100, 0b01100, 0b00100, 0b00100, 0b00100, 0b00100, 0b01110),
    0x2: (0b01110, 0b10001, 0b00001, 0b00010, 0b00100, 0b01000, 0b11111),
    0x3: (0b11110, 0b00001, 0b00001, 0b01110, 0b00001, 0b00001, 0b11110),
    0x4: (0b00010, 0b00110, 0b01010, 0b10010, 0b11111, 0b00010, 0b00010),
    0x5: (0b11111, 0b10000, 0b11110, 0b00001, 0b00001, 0b10001, 0b01110),
    0x6: (0b00110, 0b01000, 0b10000, 0b11110, 0b10001, 0b10001, 0b01110),
    0x7: (0b11111, 0b00001, 0b00010, 0b00100, 0b01000, 0b01000, 0b01000),
    0x8: (0b01110, 0b10001, 0b10001, 0b01110, 0b10001, 0b10001, 0b01110),
    0x9: (0b01110, 0b10001, 0b10001, 0b01111, 0b00001, 0b00010, 0b11100),
    0xA: (0b01110, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001, 0b10001),
    0xB: (0b11110, 0b10001, 0b10001, 0b11110, 0b10001, 0b10001, 0b11110),
    0xC: (0b01110, 0b10001, 0b10000, 0b10000, 0b10000, 0b10001, 0b01110),
    0xD: (0b11110, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11110),
    0xE: (0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b11111),
    0xF: (0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b10000),
}


def glyph(v):
    """返回 0~f 的 7 行 5 位字模（list[int]），未知值返回空格。"""
    return list(FONT_5x7.get(v & 0xF, (0,) * 7))


def render_digit(img, v, x, y, color=(255, 255, 255)):
    """在 img(BGR, (H,W,3)) 的 (x,y) 左上角画一个 5x7 字符（十六进制 v）。"""
    H, W = img.shape[:2]
    bits = FONT_5x7.get(v & 0xF, (0,) * 7)
    for row in range(7):
        yy = y + row
        if yy >= H:
            break
        for col in range(5):
            if (bits[row] >> (4 - col)) & 1:
                xx = x + col
                if xx < W:
                    img[yy, xx] = color


def render_decimal(img, value, x, y, color=(0, 255, 255), scale=1):
    """
    用 5x7 字模画一个十进制数（多位数，靠左对齐）。
    仅用 0~9 字形。这是显示层的计数显示（FPGA Phase C 用字模 ROM）。
    """
    s = str(int(value))
    for i, ch in enumerate(s):
        v = ord(ch) - ord("0")
        render_digit(img, v, x + i * 6 * scale, y, color)


# 缓存：把字模转成 numpy 便于叠加（预留，若未来需要向量化 ID 叠加）
_GLYPH_NP = {k: np.unpackbits(np.array(v, dtype=np.uint8)[:, None],
                              axis=1)[:, :5] for k, v in FONT_5x7.items()}
